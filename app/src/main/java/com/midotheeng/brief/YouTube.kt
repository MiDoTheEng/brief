package com.midotheeng.brief

import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.downloader.Downloader
import org.schabi.newpipe.extractor.downloader.Request
import org.schabi.newpipe.extractor.downloader.Response
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import org.schabi.newpipe.extractor.services.youtube.YoutubeParsingHelper
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import java.io.File
import java.net.HttpURLConnection
import java.net.URL

/**
 * YouTube: first tries the video's captions (instant, uses no Groq quota for listening),
 * otherwise downloads just the audio.
 */
object YouTube {
    private const val UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:128.0) Gecko/20100101 Firefox/128.0"
    @Volatile private var ready = false

    class Result(val title: String, val channel: String, val durationSec: Long, val transcript: String?, val audio: File?)

    fun matches(url: String): Boolean {
        val host = Regex("""https?://([^/?#]+)""").find(url)?.groupValues?.get(1)?.lowercase().orEmpty()
        return host.endsWith("youtube.com") || host.endsWith("youtu.be") || host.endsWith("youtube-nocookie.com")
    }

    private fun init() {
        if (ready) return
        synchronized(this) { if (!ready) { NewPipe.init(Dl); ready = true } }
    }

    fun load(url: String, cacheDir: File, progress: (String) -> Unit): Result {
        init()
        progress("Reading YouTube video…")
        val info = try { StreamInfo.getInfo(ServiceList.YouTube, clean(url)) } catch (e: Exception) {
            throw BriefException("YouTube didn't open this video (${e.message?.take(120)}). It may be private, age-restricted or a live stream.")
        }
        val title = info.name.orEmpty()
        val channel = info.uploaderName.orEmpty()
        val dur = info.duration

        // 1) Captions
        val transcript = try { captions(info) } catch (e: Exception) { null }
        if (!transcript.isNullOrBlank() && transcript.length > 200) return Result(title, channel, dur, transcript, null)

        // 2) Audio only
        val streams = info.audioStreams.filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
        if (streams.isEmpty()) throw BriefException("YouTube didn't give an audio stream for this video.")
        val pick = streams.filter { it.format == MediaFormat.M4A }.minByOrNull { b -> b.averageBitrate.takeIf { it > 0 } ?: Int.MAX_VALUE }
            ?: streams.minByOrNull { b -> b.averageBitrate.takeIf { it > 0 } ?: Int.MAX_VALUE }!!
        val ext = if (pick.format == MediaFormat.M4A) "m4a" else "webm"
        val out = File(cacheDir, "yt_audio.$ext")
        download(pick.content, out, progress)
        return Result(title, channel, dur, null, out)
    }

    private fun clean(url: String): String {
        // youtube.com/shorts/ID and youtu.be/ID?si=… are both fine for NewPipe; drop tracking junk.
        return url.replace(Regex("""[?&]si=[^&]*"""), "").replace(Regex("""[?&]feature=[^&]*"""), "")
    }

    private fun captions(info: StreamInfo): String? {
        val vtt = info.subtitles.filter { it.format == MediaFormat.VTT && it.isUrl }
        if (vtt.isEmpty()) return null
        val auto = vtt.firstOrNull { it.isAutoGenerated }
        val original = auto?.languageTag?.substringBefore('-')
        val pick = vtt.firstOrNull { !it.isAutoGenerated && original != null && it.languageTag.startsWith(original) }
            ?: auto
            ?: vtt.firstOrNull { !it.isAutoGenerated && (it.languageTag.startsWith("en") || it.languageTag.startsWith("ar")) }
            ?: vtt.first()
        val body = Dl.get(pick.content).responseBody()
        return Transcript.fromVtt(body)
    }

    /** Downloads in pieces, the way YouTube expects, so it isn't throttled. */
    private fun download(url: String, out: File, progress: (String) -> Unit) {
        val web = try { YoutubeParsingHelper.isWebStreamingUrl(url) } catch (e: Throwable) { false }
        val ua = if (try { YoutubeParsingHelper.isVisionOsStreamingUrl(url) } catch (e: Throwable) { false })
            YoutubeParsingHelper.getVisionOsUserAgent(null) else UA
        val chunk = 2L * 1024 * 1024
        var pos = 0L
        var total = -1L
        out.outputStream().use { os ->
            while (total < 0 || pos < total) {
                val end = pos + chunk - 1
                val sep = if (url.contains('?')) "&" else "?"
                val c = URL("$url${sep}range=$pos-$end").openConnection() as HttpURLConnection
                c.connectTimeout = 15000; c.readTimeout = 30000
                c.setRequestProperty("User-Agent", ua)
                c.setRequestProperty("Origin", "https://www.youtube.com")
                c.setRequestProperty("Referer", "https://www.youtube.com/")
                if (web) {
                    c.requestMethod = "POST"; c.doOutput = true
                    c.outputStream.use { it.write(byteArrayOf(0x78, 0)) }
                }
                try {
                    val code = c.responseCode
                    if (code !in 200..299) throw BriefException("YouTube refused the audio download (HTTP $code). Try again, or download the video and share the file.")
                    if (total < 0) {
                        total = c.getHeaderField("Content-Range")?.substringAfter('/')?.toLongOrNull()
                            ?: Regex("""[?&]clen=(\d+)""").find(url)?.groupValues?.get(1)?.toLongOrNull()
                            ?: -2L
                    }
                    var got = 0L
                    c.inputStream.use { ins ->
                        val b = ByteArray(64 * 1024)
                        while (true) { val n = ins.read(b); if (n < 0) break; os.write(b, 0, n); got += n }
                    }
                    pos += got
                    if (got == 0L || total == -2L) break
                    if (total > 0) progress("Downloading YouTube audio… ${pos * 100 / total}%")
                } finally { c.disconnect() }
            }
        }
        if (out.length() < 1024) throw BriefException("YouTube audio download came back empty.")
    }

    /** NewPipe's way of making web requests. */
    private object Dl : Downloader() {
        override fun execute(request: Request): Response {
            val c = URL(request.url()).openConnection() as HttpURLConnection
            c.instanceFollowRedirects = true
            c.connectTimeout = 15000; c.readTimeout = 30000
            c.requestMethod = request.httpMethod()
            var hasUa = false
            request.headers().forEach { (k, vs) ->
                if (k.equals("User-Agent", true)) hasUa = true
                c.setRequestProperty(k, vs.joinToString(", "))
            }
            if (!hasUa) c.setRequestProperty("User-Agent", UA)
            request.dataToSend()?.let { data ->
                c.doOutput = true
                c.outputStream.use { it.write(data) }
            }
            try {
                val code = c.responseCode
                if (code == 429) throw ReCaptchaException("reCaptcha Challenge requested", request.url())
                val stream = if (code in 200..399) c.inputStream else c.errorStream
                val body = stream?.bufferedReader()?.use { it.readText() }
                val headers = c.headerFields.filterKeys { it != null }.mapValues { it.value.toList() }
                return Response(code, c.responseMessage ?: "", headers, body, c.url.toString())
            } finally { c.disconnect() }
        }
    }
}
